using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;

namespace Gooby.Unity.World
{
    /// <summary>
    /// The rendering mood of the concept boards: warm late-afternoon key light with soft shadows, a pastel
    /// sky/ground ambient, and a global post-processing volume (bloom, vignette, warm grade, gentle depth of
    /// field for the room dioramas). Everything is created from code so the Boot scene stays empty.
    /// </summary>
    public static class SceneDressing
    {
        public sealed class Rig
        {
            public Light Sun;
            public Light Fill;
            public Light Lamp;
            public Light WindowSun;
            public ParticleSystem SunMotes;
            public Volume Volume;
            public VolumeProfile Profile;
            public DepthOfField DepthOfField;
            public ColorAdjustments ColorAdjustments;
            public WhiteBalance WhiteBalance;
            public Vignette Vignette;
        }

        public static Rig Create(Transform root, Camera camera)
        {
            var rig = new Rig();

            var sunGo = new GameObject("Sun");
            sunGo.transform.SetParent(root, false);
            rig.Sun = sunGo.AddComponent<Light>();
            rig.Sun.type = LightType.Directional;
            rig.Sun.color = ArtLibrary.Hex("FFE9CF");
            rig.Sun.intensity = 1.1f;
            rig.Sun.shadows = LightShadows.Soft;
            rig.Sun.shadowStrength = 0.8f;
            sunGo.transform.rotation = Quaternion.Euler(52f, -28f, 0f);

            // cool fill from the opposite side keeps shadowed sides pastel instead of muddy
            var fillGo = new GameObject("Fill");
            fillGo.transform.SetParent(root, false);
            rig.Fill = fillGo.AddComponent<Light>();
            rig.Fill.type = LightType.Directional;
            rig.Fill.color = ArtLibrary.Hex("BFD8FF");
            rig.Fill.intensity = 0.12f;
            rig.Fill.shadows = LightShadows.None;
            fillGo.transform.rotation = Quaternion.Euler(30f, 150f, 0f);

            // the living-room floor lamp (board 08, front-left corner): a warm pool of light on floor and sofa
            var lampGo = new GameObject("Lamp");
            lampGo.transform.SetParent(root, false);
            lampGo.transform.position = new Vector3(-1.8f, 1.75f, 1.2f);
            rig.Lamp = lampGo.AddComponent<Light>();
            rig.Lamp.type = LightType.Point;
            rig.Lamp.color = ArtLibrary.Hex("FFD9A0");
            rig.Lamp.intensity = 1.0f;
            rig.Lamp.range = 6.0f;
            rig.Lamp.shadows = LightShadows.None;

            // late sun through the east window (board 08): an orange spot that pools on the floor by the armchair
            var windowGo = new GameObject("WindowSun");
            windowGo.transform.SetParent(root, false);
            windowGo.transform.position = new Vector3(3.6f, 2.4f, 0.9f);
            windowGo.transform.rotation = Quaternion.LookRotation(new Vector3(-1.6f, -1.55f, -0.35f).normalized, Vector3.up);
            rig.WindowSun = windowGo.AddComponent<Light>();
            rig.WindowSun.type = LightType.Spot;
            rig.WindowSun.color = ArtLibrary.Hex("FFC890");
            rig.WindowSun.intensity = 2.2f;
            rig.WindowSun.range = 10f;
            rig.WindowSun.spotAngle = 62f;
            rig.WindowSun.innerSpotAngle = 30f;
            rig.WindowSun.shadows = LightShadows.None;
            // motes drifting down the shaft make the pool on the floor read as light in the air (parented: they move with the spot)
            rig.SunMotes = Effects.SunMotes(windowGo.transform, windowGo.transform.position, windowGo.transform.forward, 4.2f, 0.45f);

            // The ambient is deliberately well below white: sun + ambient + fill must stay near 1× albedo on a lit
            // surface, otherwise every pastel clips to its own colour and the soft shadows of the boards vanish
            // (they did — a white plane under the old rig showed no shadow at all).
            RenderSettings.ambientMode = AmbientMode.Trilight;
            SetAmbient(ArtLibrary.Hex("D8E9FF"), ArtLibrary.Hex("FFE6D0"), ArtLibrary.Hex("D6C3A8"), 0.55f);
            RenderSettings.fog = false;

            var camData = camera.GetUniversalAdditionalCameraData();
            camData.renderPostProcessing = true;
            camData.antialiasing = AntialiasingMode.FastApproximateAntialiasing;
            camData.renderShadows = true;
            camData.dithering = true;
            camera.allowHDR = true;

            // the serialized profile (Resources/gooby-art/GoobyLook, generated by Gooby.Editor.ArtAssets) keeps the
            // post-processing shaders in player builds; a runtime clone is driven per scene below
            var template = Resources.Load<VolumeProfile>("gooby-art/GoobyLook");
            rig.Profile = template != null ? Object.Instantiate(template) : ScriptableObject.CreateInstance<VolumeProfile>();
            rig.Profile.name = "GoobyLook (runtime)";
            if (template == null) Debug.LogWarning("[look] GoobyLook profile missing — post-processing may be stripped from builds");
            var bloom = Get<Bloom>(rig.Profile);
            bloom.intensity.Override(0.35f);
            bloom.threshold.Override(1.05f);
            bloom.scatter.Override(0.65f);
            bloom.tint.Override(ArtLibrary.Hex("FFE3C4"));
            // No tonemapper: the boards are high-key with real whites (clouds, fences, cards ≈ 250). Neutral's shoulder
            // mapped a white of 1.0 to 0.63 linear — every unlit white came out as 82 % grey and the sky's blue channel
            // was compressed towards teal. The light budget keeps lit surfaces near 1× albedo, so little clips.
            Get<Tonemapping>(rig.Profile).mode.Override(TonemappingMode.None);
            rig.ColorAdjustments = Get<ColorAdjustments>(rig.Profile);
            SetExposure(rig, 0.18f);
            rig.ColorAdjustments.contrast.Override(8f);
            rig.ColorAdjustments.saturation.Override(4f);
            rig.ColorAdjustments.colorFilter.Override(ArtLibrary.Hex("FFF6EC"));
            rig.WhiteBalance = Get<WhiteBalance>(rig.Profile);
            rig.WhiteBalance.temperature.Override(IndoorWarmth);
            rig.Vignette = Get<Vignette>(rig.Profile);
            rig.Vignette.intensity.Override(0.22f);
            rig.Vignette.smoothness.Override(0.55f);
            rig.Vignette.color.Override(ArtLibrary.Hex("5A3E2E"));
            rig.DepthOfField = Get<DepthOfField>(rig.Profile);
            rig.DepthOfField.mode.Override(DepthOfFieldMode.Gaussian);
            rig.DepthOfField.gaussianStart.Override(9f);
            rig.DepthOfField.gaussianEnd.Override(16f);
            rig.DepthOfField.gaussianMaxRadius.Override(1.0f);
            rig.DepthOfField.highQualitySampling.Override(true);

            var volGo = new GameObject("PostVolume");
            volGo.transform.SetParent(root, false);
            rig.Volume = volGo.AddComponent<Volume>();
            rig.Volume.isGlobal = true;
            rig.Volume.priority = 10f;
            rig.Volume.sharedProfile = rig.Profile;
            return rig;
        }

        /// <summary>
        /// Exposure of the grade in EV. The per-scene values were balanced under the Neutral tonemapper; without one
        /// the same mid-tones need <see cref="ToneShift"/> less (Neutral put 0.575 linear at 0.46, ×0.82 does the same),
        /// while a white of 1.0 now lands at 0.94 linear instead of 0.63.
        /// </summary>
        public static void SetExposure(Rig rig, float ev) => rig.ColorAdjustments.postExposure.Override(ev + ToneShift);
        public const float ToneShift = -0.28f;

        private static T Get<T>(VolumeProfile profile) where T : VolumeComponent
        {
            if (profile.TryGet<T>(out var c)) { c.active = true; return c; }
            return profile.Add<T>(true);
        }

        /// <summary>Trilight ambient from three palette colours scaled by <paramref name="k"/> (the light budget).</summary>
        private static void SetAmbient(Color sky, Color equator, Color ground, float k)
        {
            RenderSettings.ambientSkyColor = sky * k;
            RenderSettings.ambientEquatorColor = equator * k;
            RenderSettings.ambientGroundColor = ground * k;
        }

        /// <summary>
        /// Outdoor light for a local hour (Core DayPhase curve): noon is the board-03 look, dusk goes golden, night
        /// turns the sun into cool moonlight with a dark blue sky and lifted vignette. Returns the sky/background
        /// colour the camera should clear with. Call after <see cref="SetIndoor"/>(false).
        /// </summary>
        public static Color SetTimeOfDay(Rig rig, double hour, Color daySky)
        {
            if (rig == null) return daySky;
            var d = (float)Gooby.Core.Time.DayPhase.Daylight(hour);
            var w = (float)Gooby.Core.Time.DayPhase.Warmth(hour);
            // the afternoon of board 03 is bright and only faintly golden (blue sky, cream light); the strong amber
            // belongs to dawn and dusk, so the warmth only bites once the daylight itself starts to fade
            var gold = w * Mathf.Lerp(1f, 0.35f, d);
            var sunColor = Color.Lerp(Color.Lerp(ArtLibrary.Hex("7D8FC4"), ArtLibrary.Hex("FFEBCC"), d), ArtLibrary.Hex("FFB870"), gold * 0.6f);
            rig.Sun.color = sunColor;
            rig.Sun.intensity = Mathf.Lerp(0.45f, 1.15f, d);
            rig.Sun.shadowStrength = Mathf.Lerp(0.5f, 0.82f, d);
            rig.Sun.transform.rotation = Quaternion.Euler(Mathf.Lerp(28f, 47f, d) - w * 14f, -36f, 0f);
            rig.Fill.intensity = Mathf.Lerp(0.06f, 0.12f, d);
            SetAmbient(Color.Lerp(ArtLibrary.Hex("2A3A62"), ArtLibrary.Hex("CFE6FF"), d),
                Color.Lerp(ArtLibrary.Hex("3E4870"), ArtLibrary.Hex("F2EBDD"), d),
                Color.Lerp(ArtLibrary.Hex("262838"), ArtLibrary.Hex("B7C9A0"), d), Mathf.Lerp(0.7f, 0.5f, d));
            SetExposure(rig, Mathf.Lerp(-0.15f, 0.2f, d));
            rig.ColorAdjustments.contrast.Override(Mathf.Lerp(10f, 8f, d));
            rig.ColorAdjustments.saturation.Override(Mathf.Lerp(-8f, 8f, d));
            rig.ColorAdjustments.colorFilter.Override(Color.Lerp(Color.Lerp(ArtLibrary.Hex("B8C4E6"), ArtLibrary.Hex("FFF8F0"), d), ArtLibrary.Hex("FFC878"), gold * 0.6f));
            rig.Vignette.intensity.Override(Mathf.Lerp(0.34f, 0.14f, d));
            return Color.Lerp(Color.Lerp(ArtLibrary.Hex("141B33"), daySky, d), ArtLibrary.Hex("FFB48A"), gold * 0.72f);
        }

        /// <summary>Moves the window sun to the east wall of the staged room so its pool lands inside whatever room is up.</summary>
        public static void PlaceWindowSun(Rig rig, float halfWidth, float depth)
        {
            if (rig?.WindowSun == null) return;
            rig.WindowSun.transform.position = new Vector3(halfWidth + 0.6f, 2.4f, 0.18f * depth);
            AnchorSunCookie(rig, new Vector3(halfWidth * 0.35f, 0f, -0.15f * depth));
        }

        /// <summary>The indoor sun stands low in the east (board 08): light through the right-hand window, shadows towards the door wall.</summary>
        private static readonly Quaternion IndoorSun = Quaternion.Euler(38f, -62f, 0f);
        private const float CookieSizeM = 7.5f;

        /// <summary>
        /// Puts the sun's window cookie over a floor point: a directional cookie is projected along the light's
        /// forward from its transform, so the light stands back up its own ray from the point the panes should hit.
        /// </summary>
        public static void AnchorSunCookie(Rig rig, Vector3 floorPoint)
        {
            if (rig?.Sun == null) return;
            rig.Sun.transform.position = floorPoint - IndoorSun * Vector3.forward * 8f;
        }

        /// <summary>
        /// The window panes are the home's light (board 08); the shops of board 10 are lit high-key by their ceiling
        /// lamps, so an interior takes the cookie off again (and gets the plain indoor sun back).
        /// </summary>
        public static void SetWindowCookie(Rig rig, bool on)
        {
            if (rig?.Sun == null) return;
            rig.Sun.cookie = on ? WindowCookie() : null;
            rig.Sun.intensity = on ? IndoorSunIntensity : 1.0f;
        }

        /// <summary>Indoor key with the window cookie: the panes get the full value, the rest of the room 0.3 of it.</summary>
        private const float IndoorSunIntensity = 1.6f;

        private static Texture2D _windowCookie;

        /// <summary>
        /// Board 08's sunlight: the room is not lit evenly but through the window — two tall panes of sun on the
        /// floor and furniture, the rest of the room in a gentle shade. A soft-edged cookie on the directional sun
        /// (base 0.3, panes 1.0) does it for every room; outdoors the cookie comes off again.
        /// </summary>
        private static Texture2D WindowCookie()
        {
            if (_windowCookie != null) return _windowCookie;
            const int n = 256;
            var tex = new Texture2D(n, n, TextureFormat.RGBA32, false) { wrapMode = TextureWrapMode.Clamp, filterMode = FilterMode.Bilinear, name = "window_cookie" };
            var px = new Color[n * n];
            for (var y = 0; y < n; y++)
                for (var x = 0; x < n; x++)
                {
                    var u = (x + 0.5f) / n; var v = (y + 0.5f) / n;
                    var lit = 0f;
                    foreach (var cx in new[] { 0.35f, 0.65f })
                    {
                        // rounded pane: distance outside a 0.24 × 0.6 box, faded over 4 % (the mullion between stays dark)
                        var dx = Mathf.Max(0f, Mathf.Abs(u - cx) - 0.12f);
                        var dy = Mathf.Max(0f, Mathf.Abs(v - 0.5f) - 0.30f);
                        var d = Mathf.Sqrt(dx * dx + dy * dy);
                        lit = Mathf.Max(lit, 1f - Mathf.SmoothStep(0f, 1f, d / 0.04f));
                    }
                    var g = Mathf.Lerp(0.3f, 1f, lit);
                    px[y * n + x] = new Color(g, g, g, 1f);
                }
            tex.SetPixels(px);
            tex.Apply(false, true);
            return _windowCookie = tex;
        }

        /// <summary>
        /// Atmospheric perspective for the street (board 03): the far blocks, the avenue's end and the painted
        /// mountains fade a little towards the sky colour — the depth cue every board paints in, and the one a
        /// scene of crisp models lacks. Exp² and faint, so the near town stays saturated; indoors and in the small
        /// garden it is off (the haze would only grey a 30 m lawn). The camera clear colour stays the pure sky.
        /// </summary>
        public static void SetHaze(bool on, Color sky)
        {
            RenderSettings.fog = on;
            if (!on) return;
            RenderSettings.fogMode = FogMode.ExponentialSquared;
            RenderSettings.fogDensity = HazeDensity;
            RenderSettings.fogColor = Color.Lerp(sky, Color.white, 0.2f);
        }

        /// <summary>≈13 % haze at 230 m (the clouds), ≈24 % at the 330 m horizon painting.</summary>
        public const float HazeDensity = 0.0016f;

        /// <summary>
        /// The weather on top of the hour's light (city_ambiente.gd wetter_licht_profil): under clouds the sun is weaker,
        /// greyer and its shadows softer, the ambient a little dimmer, the sky turns toward a soft overcast grey (the night
        /// sky stays dark) and misty days bring fog — thicker in the 30-m garden than over the town. A sunny day keeps the
        /// board look untouched: the greying starts above the clear sky's own cloud cover. Call after
        /// <see cref="SetTimeOfDay"/> and <see cref="SetHaze"/>; returns the sky colour to clear with.
        /// </summary>
        public static Color ApplyWeather(Rig rig, Gooby.Core.Life.WetterFx.Plan plan, double hour, Color sky, bool garden)
        {
            if (rig == null || plan == null) return sky;
            var d = (float)Gooby.Core.Time.DayPhase.Daylight(hour);
            var truebe = Overcast(plan);
            rig.Sun.intensity *= (float)plan.SonnenFaktor;
            rig.Sun.color = Color.Lerp(rig.Sun.color, new Color(0.82f, 0.84f, 0.88f), truebe * 0.55f);
            rig.Sun.shadowStrength *= Mathf.Lerp(1f, 0.6f, truebe);
            var a = (float)plan.AmbientFaktor;
            RenderSettings.ambientSkyColor *= a;
            RenderSettings.ambientEquatorColor *= a;
            RenderSettings.ambientGroundColor *= a;
            // a darker day needs a little lift, or a storm reads as dusk
            rig.ColorAdjustments.postExposure.Override(rig.ColorAdjustments.postExposure.value + 0.3f * truebe);
            rig.ColorAdjustments.saturation.Override(rig.ColorAdjustments.saturation.value - 10f * truebe);
            var grey = Color.Lerp(ArtLibrary.Hex("1C2233"), ArtLibrary.Hex("B4BECB"), d);
            if (plan.Nebel > 0.01)
            {
                var density = (garden ? 0.034f : 0.015f) * (float)plan.Nebel;
                RenderSettings.fogMode = FogMode.ExponentialSquared;
                RenderSettings.fogDensity = RenderSettings.fog ? Mathf.Max(RenderSettings.fogDensity, density) : density;
                RenderSettings.fogColor = Color.Lerp(grey, Color.white, 0.12f);
                RenderSettings.fog = true;
            }
            return Color.Lerp(sky, grey, truebe * 0.85f);
        }

        /// <summary>0 for a sunny sky (its own light cloud cover included) … 1 for a thunderstorm overcast.</summary>
        public static float Overcast(Gooby.Core.Life.WetterFx.Plan plan)
        {
            if (plan == null) return 0f;
            var clear = Gooby.Core.Life.RanchWetter.BewoelkungVon("sonne") * 0.55;
            var storm = Gooby.Core.Life.RanchWetter.BewoelkungVon("gewitter") * 0.55;
            return Mathf.Clamp01((float)((plan.Grau - clear) / (storm - clear)));
        }

        /// <summary>Far-field focus (street, interiors): a Gaussian softening beyond <paramref name="blurredFrom"/> metres.</summary>
        public static void SetFocus(Rig rig, float sharpUntil, float blurredFrom)
        {
            if (rig?.DepthOfField == null) return;
            rig.DepthOfField.active = blurredFrom > sharpUntil && GraphicsQuality.DepthOfFieldAllowed;
            rig.DepthOfField.mode.Override(DepthOfFieldMode.Gaussian);
            rig.DepthOfField.gaussianStart.Override(sharpUntil);
            rig.DepthOfField.gaussianEnd.Override(blurredFrom);
        }

        /// <summary>
        /// Tilt-shift diorama of boards 01/02/05/09: the stage is sharp, the near fence and corner plants and the far
        /// wall or cottage roof soften on both sides of it. Bokeh, because URP's Gaussian mode only blurs the far
        /// field; a moderate aperture so beds and cards at the frame's bottom stay readable.
        /// </summary>
        public static void SetDioramaFocus(Rig rig, float focusDistance, float focalLength = 70f, float aperture = 3.4f)
        {
            if (rig?.DepthOfField == null) return;
            rig.DepthOfField.active = GraphicsQuality.DepthOfFieldAllowed;
            rig.DepthOfField.mode.Override(DepthOfFieldMode.Bokeh);
            rig.DepthOfField.focusDistance.Override(focusDistance);
            rig.DepthOfField.focalLength.Override(focalLength);
            rig.DepthOfField.aperture.Override(aperture);
            rig.DepthOfField.bladeCount.Override(5);
        }

        /// <summary>
        /// Indoor (home, room build): warm golden key light with firm soft shadows, cosy grade, floor lamp on.
        /// Outdoor (garden, city): neutral daylight so lawns stay green and the sky blue, a firmer shadow and a touch
        /// more contrast and saturation (boards 03/05 are richer than the pastel rooms); lamp off.
        /// </summary>
        public static void SetIndoor(Rig rig, bool indoor)
        {
            if (rig == null) return;
            // indoors the sun stands low in the east so the light falls in through the right-hand window and the
            // shadows stretch towards the door wall, as on board 08. Its warmth is modest: the honey of board 01 is
            // the floor's own tint plus the lamp and window pools — sun, filter and white balance each taking blue
            // out again stacked to ×0.46 and turned the whole floor orange (wood saturation 186 against the board's 127)
            rig.Sun.color = indoor ? ArtLibrary.Hex("FFE2C4") : ArtLibrary.Hex("FFEBCC");
            // indoors the cookie dims the sun to 0.3 outside the window panes, so the key is stronger to keep the panes bright
            rig.Sun.intensity = indoor ? IndoorSunIntensity : 1.15f;
            rig.Sun.shadowStrength = indoor ? 0.72f : 0.82f;
            rig.Sun.transform.rotation = indoor ? IndoorSun : Quaternion.Euler(47f, -36f, 0f);
            rig.Sun.cookie = indoor ? WindowCookie() : null;
            var cookieData = rig.Sun.GetUniversalAdditionalLightData();
            cookieData.lightCookieSize = new Vector2(CookieSizeM, CookieSizeM);
            cookieData.lightCookieOffset = Vector2.zero;
            rig.Fill.intensity = indoor ? 0.1f : 0.12f;
            rig.Fill.color = ArtLibrary.Hex("BFD8FF");   // SetSpace tints it blue
            rig.Lamp.enabled = indoor;
            rig.WindowSun.enabled = indoor;
            rig.WindowSun.intensity = 2.2f;
            if (rig.SunMotes != null) rig.SunMotes.gameObject.SetActive(indoor);
            if (indoor) RenderSettings.fog = false;   // the street's haze never follows Gooby into a room
            if (indoor) SetAmbient(ArtLibrary.Hex("DACDC0"), ArtLibrary.Hex("E6C6A6"), ArtLibrary.Hex("9A7B60"), 0.62f);
            else SetAmbient(ArtLibrary.Hex("CFE6FF"), ArtLibrary.Hex("F2EBDD"), ArtLibrary.Hex("B7C9A0"), 0.5f);
            SetExposure(rig, indoor ? 0.12f : 0.2f);
            rig.ColorAdjustments.contrast.Override(indoor ? 10f : 8f);
            rig.ColorAdjustments.saturation.Override(indoor ? 0f : 8f);
            rig.ColorAdjustments.colorFilter.Override(indoor ? ArtLibrary.Hex("FFF1E2") : ArtLibrary.Hex("FFF8F0"));
            rig.WhiteBalance?.temperature.Override(indoor ? IndoorWarmth : OutdoorWarmth);
            rig.Vignette.intensity.Override(indoor ? 0.26f : 0.14f);
        }

        /// <summary>
        /// White balance of the grade: the rooms lean warm (board 08's honey light). Outdoors the cream sun and the
        /// warm filter already tint the frame, and a third warm shift on top took the blue out of every green —
        /// lawns went lime and trees olive — so the street and garden keep the balance near neutral.
        /// </summary>
        public const float IndoorWarmth = 3f, OutdoorWarmth = 1.5f;

        /// <summary>
        /// Board 02 build mode: the room seen from high up is bright, airy and only faintly warm — the low window sun
        /// and the vignette of the cosy board-08 frame would wash the whole diorama amber from that angle.
        /// </summary>
        public static void SetRoomBuildGrade(Rig rig)
        {
            if (rig == null) return;
            rig.WindowSun.intensity = 1.1f;
            SetExposure(rig, 0.16f);
            rig.ColorAdjustments.contrast.Override(8f);
            rig.ColorAdjustments.saturation.Override(4f);
            rig.ColorAdjustments.colorFilter.Override(ArtLibrary.Hex("FFF4E8"));
            rig.WhiteBalance?.temperature.Override(OutdoorWarmth);   // the lawn and hedges around the shell stay green
            // a lighter, cooler ambient than the cosy room: sky light on the greenery outside the walls, an airy shell inside
            SetAmbient(ArtLibrary.Hex("E2E6E4"), ArtLibrary.Hex("EAD9C4"), ArtLibrary.Hex("A69C84"), 0.7f);
            rig.Vignette.intensity.Override(0.12f);
        }

        /// <summary>GOOB-1: cool cabin key, no window cookie, star-dark ambient (raumstation.gd sky uniforms).</summary>
        public static void SetSpace(Rig rig)
        {
            if (rig == null) return;
            rig.Sun.color = ArtLibrary.Hex("D0D8FF");
            rig.Sun.intensity = 0.55f;
            rig.Sun.shadowStrength = 0.5f;
            rig.Sun.transform.rotation = Quaternion.Euler(-50f, -25f, 0f);
            rig.Sun.cookie = null;
            rig.Fill.intensity = 0.12f;
            rig.Fill.color = ArtLibrary.Hex("8AA0D8");
            rig.Lamp.enabled = false;
            rig.WindowSun.enabled = false;
            if (rig.SunMotes != null) rig.SunMotes.gameObject.SetActive(false);
            RenderSettings.fog = false;
            SetAmbient(ArtLibrary.Hex("1A2240"), ArtLibrary.Hex("2A3050"), ArtLibrary.Hex("12141C"), 1f);
            SetExposure(rig, 0.04f);
            rig.ColorAdjustments.contrast.Override(8f);
            rig.ColorAdjustments.saturation.Override(4f);
            rig.ColorAdjustments.colorFilter.Override(ArtLibrary.Hex("E4E8FF"));
            rig.Vignette.intensity.Override(0.24f);
        }

    }
}
