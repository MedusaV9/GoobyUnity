using System.Collections.Generic;
using UnityEngine;

namespace Gooby.Unity.World
{
    /// <summary>
    /// Materials and textures of the new look (docs/concept): the painterly textures built by
    /// tools/art/build_art.py live in Resources/gooby-art. Every material is created once and shared, so the
    /// procedural world builders stay allocation-light and a colour tweak here changes every screen.
    /// </summary>
    public static class ArtLibrary
    {
        private static readonly Dictionary<string, Material> Materials = new Dictionary<string, Material>();
        private static readonly Dictionary<string, Texture2D> Textures = new Dictionary<string, Texture2D>();
        private static Shader _lit;

        public static Shader Lit => _lit ??= Shader.Find("Universal Render Pipeline/Lit") ?? Shader.Find("Standard");

        /// <summary>
        /// Runtime materials are cloned from the serialized templates in Resources/gooby-art/materials (generated by
        /// Gooby.Editor.ArtAssets). URP strips shader variants no asset references, so keywords such as
        /// _ALPHATEST_ON only survive in player builds when a material asset carries them.
        /// </summary>
        private static Material Template(string name, Shader fallback)
        {
            var t = Resources.Load<Material>("gooby-art/materials/" + name);
            if (t != null) return new Material(t);
            Debug.LogWarning("[art] material template missing: " + name + " (run GOOBY/Generate art assets)");
            return new Material(fallback);
        }

        public static Texture2D Tex(string name)
        {
            if (Textures.TryGetValue(name, out var t)) return t;
            t = Resources.Load<Texture2D>("gooby-art/" + name);
            if (t == null) Debug.LogWarning("[art] texture missing: gooby-art/" + name);
            Textures[name] = t;
            return t;
        }

        /// <summary>Plain matte colour (walls, furniture stand-ins, UI-coloured props).</summary>
        public static Material Solid(Color color, float smoothness = 0.18f)
        {
            var key = "solid:" + ColorUtility.ToHtmlStringRGBA(color) + ":" + smoothness;
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_opaque", Lit);
            m.name = key;
            SetColor(m, color);
            SetSmoothness(m, smoothness);
            Materials[key] = m;
            return m;
        }

        /// <summary>Tiled texture (floor boards, lawn, asphalt). Tint multiplies the texture.</summary>
        public static Material Textured(string texture, Vector2 tiling, Color? tint = null, float smoothness = 0.12f)
        {
            var key = "tex:" + texture + ":" + tiling + ":" + (tint.HasValue ? ColorUtility.ToHtmlStringRGBA(tint.Value) : "-");
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_opaque", Lit);
            m.name = key;
            var tex = Tex(texture);
            if (tex != null)
            {
                m.mainTexture = tex;
                if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
                m.mainTextureScale = tiling;
                if (m.HasProperty("_BaseMap")) m.SetTextureScale("_BaseMap", tiling);
            }
            SetColor(m, tint ?? Color.white);
            SetSmoothness(m, smoothness);
            Materials[key] = m;
            return m;
        }

        /// <summary>A lit material over a generated texture (the "Gestalten" wall/floor patterns), cached by key + tiling.</summary>
        public static Material Textured(Texture2D tex, string key, Vector2 tiling, float smoothness = 0.12f)
        {
            var k = "gtex:" + key + ":" + tiling;
            if (Materials.TryGetValue(k, out var m)) return m;
            m = Template("lit_opaque", Lit);
            m.name = k;
            m.mainTexture = tex;
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
            m.mainTextureScale = tiling;
            if (m.HasProperty("_BaseMap")) m.SetTextureScale("_BaseMap", tiling);
            SetColor(m, Color.white);
            SetSmoothness(m, smoothness);
            Materials[k] = m;
            return m;
        }

        /// <summary>
        /// Tinted CC0 surface (tools/art/fetch_pbr.py → Resources/gooby-art/pbr): colour/detail map plus tangent-space
        /// normal map, tiled in world metres via <paramref name="metresPerTile"/> (the Blender models carry box UVs
        /// with 1 unit = 1 m; the generated slabs set their own tiling). Detail maps are mid-grey grain, so the tint is
        /// the colour you see; the normal map adds the relief that makes plaster, wood, cloth and tiles read as such.
        /// </summary>
        public static Material Pbr(string surface, float metresPerTile, Color tint, float smoothness = 0.2f, float normalScale = 1f) =>
            Pbr(surface, Vector2.one / Mathf.Max(0.01f, metresPerTile), tint, smoothness, normalScale);

        /// <summary>Surface for a generated slab of `size` metres (Unity primitives map 0..1 over a face): tiling = size / metresPerTile.</summary>
        public static Material PbrSlab(string surface, Vector2 sizeMetres, float metresPerTile, Color tint, float smoothness = 0.2f, float normalScale = 1f) =>
            Pbr(surface, new Vector2(sizeMetres.x, sizeMetres.y) / Mathf.Max(0.01f, metresPerTile), tint, smoothness, normalScale);

        public static Material Pbr(string surface, Vector2 tiling, Color tint, float smoothness = 0.2f, float normalScale = 1f)
        {
            tiling = new Vector2(Mathf.Round(tiling.x * 100f) / 100f, Mathf.Round(tiling.y * 100f) / 100f);
            var key = "pbr:" + surface + ":" + tiling + ":" + ColorUtility.ToHtmlStringRGBA(tint) + ":" + smoothness + ":" + normalScale;
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_pbr", Lit);
            m.name = key;
            var color = Tex("pbr/" + surface + "_c");
            var normal = Tex("pbr/" + surface + "_n");
            if (color != null)
            {
                m.mainTexture = color;
                m.mainTextureScale = tiling;
                if (m.HasProperty("_BaseMap")) { m.SetTexture("_BaseMap", color); m.SetTextureScale("_BaseMap", tiling); }
            }
            if (normal != null && m.HasProperty("_BumpMap"))
            {
                m.SetTexture("_BumpMap", normal);
                m.SetTextureScale("_BumpMap", tiling);
                m.SetFloat("_BumpScale", normalScale);
                m.EnableKeyword("_NORMALMAP");
            }
            SetColor(m, tint);
            SetSmoothness(m, smoothness);
            Materials[key] = m;
            return m;
        }

        /// <summary>Alpha-clipped, double-sided lit sprite (plants, flowers, tree crowns as crossed quads).</summary>
        public static Material Cutout(string texture)
        {
            var key = "cutout:" + texture;
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_cutout", Lit);
            m.name = key;
            var tex = Tex(texture);
            if (tex != null)
            {
                m.mainTexture = tex;
                if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
            }
            SetColor(m, Color.white);
            Materials[key] = m;
            return m;
        }

        /// <summary>Alpha-clipped, double-sided lit material over a texture made at runtime (fallen leaves), one per tint.</summary>
        public static Material Cutout(Texture2D tex, string key, Color tint)
        {
            key = "cutout-rt:" + key + ":" + ColorUtility.ToHtmlStringRGBA(tint);
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_cutout", Lit);
            m.name = key;
            m.mainTexture = tex;
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
            SetColor(m, tint);
            SetSmoothness(m, 0.1f);
            Materials[key] = m;
            return m;
        }

        /// <summary>Alpha-blended lit image with soft edges (sign lettering laid over a wooden board).</summary>
        public static Material Decal(string texture)
        {
            var key = "decal:" + texture;
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_transparent", Lit);
            m.name = key;
            var tex = Tex(texture);
            if (tex != null)
            {
                m.mainTexture = tex;
                if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
            }
            SetColor(m, Color.white);
            SetSmoothness(m, 0f);
            Materials[key] = m;
            return m;
        }

        /// <summary>Alpha-blended tint (build-grid overlay, ghost previews).</summary>
        public static Material Transparent(Color color)
        {
            var key = "transparent:" + ColorUtility.ToHtmlStringRGBA(color);
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("lit_transparent", Lit);
            m.name = key;
            SetColor(m, color);
            SetSmoothness(m, 0f);
            AlphaOver(m, false);
            Materials[key] = m;
            return m;
        }

        /// <summary>
        /// Blended surfaces composite their alpha "over" what is already drawn (additive ones leave it alone) instead
        /// of replacing it: the minigame stages render into a texture the UI lays over the play field, and a replaced
        /// alpha punched see-through holes in it wherever a puff or a glassy ghost was drawn.
        /// </summary>
        private static void AlphaOver(Material m, bool additive)
        {
            if (!m.HasProperty("_SrcBlendAlpha") || !m.HasProperty("_DstBlendAlpha")) return;
            m.SetFloat("_SrcBlendAlpha", (float)(additive ? UnityEngine.Rendering.BlendMode.Zero : UnityEngine.Rendering.BlendMode.One));
            m.SetFloat("_DstBlendAlpha", (float)(additive ? UnityEngine.Rendering.BlendMode.One : UnityEngine.Rendering.BlendMode.OneMinusSrcAlpha));
        }

        /// <summary>Brightest channel a glow may reach (bloom threshold is 1.05).</summary>
        public const float GlowPeak = 1.6f;

        /// <summary>Unlit solid colour; HDR values above 1 make bulbs and lamp glass bloom like the string lights of board 05.</summary>
        public static Material Glow(Color color)
        {
            var key = "glow:" + color.r + ":" + color.g + ":" + color.b;
            if (Materials.TryGetValue(key, out var m)) return m;
            // the HDR glows were authored under the Neutral tonemapper, whose shoulder rolled a 2.5 down to a cream
            // 0.9; the grade has no tonemapper now, so the same values would clip to flat white behind a halo that
            // swallows the lamp. Keep the hue, cap the peak: still above the bloom threshold, a soft halo, no blaze.
            var peak = Mathf.Max(color.r, color.g, color.b);
            if (peak > GlowPeak) color = new Color(color.r, color.g, color.b, color.a) * (GlowPeak / peak);
            m = Template("unlit_backdrop", Shader.Find("Universal Render Pipeline/Unlit") ?? Lit);
            m.name = key;
            m.mainTexture = null;
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", null);
            SetColor(m, color);
            Materials[key] = m;
            return m;
        }

        /// <summary>
        /// Particle material (URP Particles/Unlit, vertex colour × base map): alpha-blended for puffs of dust, petals
        /// and exhaust, additive for glints and fireflies. One shared material per (mode, texture).
        /// </summary>
        public static Material Particles(Texture2D texture, bool additive)
        {
            var key = "particles:" + (additive ? "add" : "alpha") + ":" + (texture != null ? texture.name : "-");
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template(additive ? "particle_additive" : "particle_alpha", Shader.Find("Universal Render Pipeline/Particles/Unlit") ?? Lit);
            m.name = key;
            m.mainTexture = texture;
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", texture);
            SetColor(m, Color.white);
            AlphaOver(m, additive);
            Materials[key] = m;
            return m;
        }

        /// <summary>Recolours every cached backdrop material of a texture (horizon panels darken at night).</summary>
        public static void TintBackdrop(string texture, Color tint)
        {
            foreach (var kv in Materials)
                if (kv.Key.StartsWith("backdrop:" + texture + ":")) SetColor(kv.Value, tint);
        }

        /// <summary>An unlit material showing a live texture (the TV's GOB.TY render texture); one per screen, not cached.</summary>
        public static Material Screen(Texture tex)
        {
            var m = Template("unlit_backdrop", Shader.Find("Universal Render Pipeline/Unlit") ?? Lit);
            m.name = "screen";
            m.mainTexture = tex;
            if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
            SetColor(m, Color.white);
            return m;
        }

        public static Material Backdrop(string texture, float topFraction = 1f, bool mirror = false)
        {
            var key = "backdrop:" + texture + ":" + topFraction + (mirror ? ":m" : "");
            if (Materials.TryGetValue(key, out var m)) return m;
            m = Template("unlit_backdrop", Shader.Find("Universal Render Pipeline/Unlit") ?? Lit);
            m.name = key;
            var tex = Tex(texture);
            if (tex != null)
            {
                m.mainTexture = tex;
                if (m.HasProperty("_BaseMap")) m.SetTexture("_BaseMap", tex);
                // a far vertical plane can only show what lies above the horizon: crop to the sky/hills band;
                // mirrored wings continue the centre panel of a Horizon fold without a visible seam
                var scale = new Vector2(mirror ? -1f : 1f, Mathf.Clamp01(topFraction));
                var offset = new Vector2(mirror ? 1f : 0f, 1f - scale.y);
                m.mainTextureScale = scale;
                m.mainTextureOffset = offset;
                if (m.HasProperty("_BaseMap")) { m.SetTextureScale("_BaseMap", scale); m.SetTextureOffset("_BaseMap", offset); }
            }
            SetColor(m, Color.white);
            Materials[key] = m;
            return m;
        }

        /// <summary>
        /// Painted horizon for the outdoor scenes: a centre panel facing -Z plus two mirrored wings folded 40°
        /// towards the viewer, so even the wide driving camera never looks past the painting. `groundCentre` is
        /// the bottom-centre of the middle panel (place it a little below ground level).
        /// </summary>
        public static Transform Horizon(Transform parent, string texture, Vector3 groundCentre, float height)
        {
            var root = new GameObject("Horizon");
            root.transform.SetParent(parent, false);
            root.transform.position = groundCentre;
            var tex = Tex(texture);
            var width = height * (tex != null ? (float)tex.width / tex.height : 1.86f);
            var size = new Vector2(width, height);
            var half = width * 0.5f;
            const float fold = 40f;
            var rad = fold * Mathf.Deg2Rad;
            Quad(root.transform, "Centre", groundCentre + Vector3.up * height * 0.5f, Quaternion.Euler(0f, 180f, 0f), size, Backdrop(texture));
            var wing = Backdrop(texture, 1f, mirror: true);
            foreach (var s in new[] { -1f, 1f })
            {
                var edge = groundCentre + new Vector3(s * half, height * 0.5f, 0f);
                var dir = new Vector3(s * Mathf.Cos(rad), 0f, -Mathf.Sin(rad));
                Quad(root.transform, "Wing", edge + dir * half, Quaternion.Euler(0f, 180f + s * fold, 0f), size, wing);
            }
            return root.transform;
        }

        // ── primitives with materials ─────────────────────────────────────────

        public static GameObject Box(Transform parent, string name, Vector3 center, Vector3 size, Material mat, bool shadows = true)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Cube);
            Prepare(go, parent, name, center, mat, shadows);
            go.transform.localScale = size;
            return go;
        }

        public static GameObject Cylinder(Transform parent, string name, Vector3 center, float radius, float height, Material mat, bool shadows = true)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Cylinder);
            Prepare(go, parent, name, center, mat, shadows);
            go.transform.localScale = new Vector3(radius * 2f, height * 0.5f, radius * 2f);
            return go;
        }

        public static GameObject Sphere(Transform parent, string name, Vector3 center, float radius, Material mat, bool shadows = true)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Sphere);
            Prepare(go, parent, name, center, mat, shadows);
            go.transform.localScale = Vector3.one * radius * 2f;
            return go;
        }

        /// <summary>Single quad facing +Z (Unity's Quad primitive faces -Z; we flip it so `rotation` reads naturally).</summary>
        public static GameObject Quad(Transform parent, string name, Vector3 center, Quaternion rotation, Vector2 size, Material mat, bool shadows = false)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Quad);
            Prepare(go, parent, name, center, mat, shadows);
            go.transform.rotation = rotation * Quaternion.Euler(0f, 180f, 0f);
            go.transform.localScale = new Vector3(size.x, size.y, 1f);
            return go;
        }

        /// <summary>Two crossed alpha-clipped quads standing on the ground: the classic stylised bush/flower/tree card.</summary>
        public static GameObject Plant(Transform parent, string texture, Vector3 groundPos, float height, float yaw = 0f)
        {
            var root = new GameObject("Plant:" + texture);
            root.transform.SetParent(parent, false);
            root.transform.position = groundPos;
            root.transform.rotation = Quaternion.Euler(0f, yaw, 0f);
            var tex = Tex(texture);
            var aspect = tex != null ? (float)tex.width / tex.height : 1f;
            var size = new Vector2(height * aspect, height);
            var mat = Cutout(texture);
            for (var i = 0; i < 2; i++)
            {
                var q = Quad(root.transform, "Card" + i, groundPos + Vector3.up * height * 0.5f, Quaternion.Euler(0f, yaw + i * 90f, 0f), size, mat, shadows: true);
                q.transform.SetParent(root.transform, true);
            }
            return root;
        }

        private static void Prepare(GameObject go, Transform parent, string name, Vector3 center, Material mat, bool shadows)
        {
            go.name = name;
            go.transform.SetParent(parent, false);
            go.transform.position = center;
            var r = go.GetComponent<Renderer>();
            r.sharedMaterial = mat;
            r.shadowCastingMode = shadows ? UnityEngine.Rendering.ShadowCastingMode.On : UnityEngine.Rendering.ShadowCastingMode.Off;
            var col = go.GetComponent<Collider>();
            if (col == null) return;
            if (Application.isPlaying) Object.Destroy(col);
            else Object.DestroyImmediate(col); // EditMode tests build world pieces outside play mode
        }

        private static void SetColor(Material m, Color c)
        {
            m.color = c;
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor", c);
        }

        private static void SetSmoothness(Material m, float s)
        {
            if (m.HasProperty("_Smoothness")) m.SetFloat("_Smoothness", s);
        }

        public static Color Hex(string hex)
        {
            ColorUtility.TryParseHtmlString(hex.StartsWith("#") ? hex : "#" + hex, out var c);
            return c;
        }
    }
